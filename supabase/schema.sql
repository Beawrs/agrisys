-- ============================================================================
--  2. CORE TABLES
--     FARMER 1:M FARM 1:M PLANTING 1:M HARVEST ;  CROP 1:M PLANTING
-- ============================================================================

create table public.farmer (
  farmer_id       integer generated by default as identity primary key,
  first_name      varchar(50)  not null check (length(btrim(first_name)) >= 1),
  last_name       varchar(50)  not null check (length(btrim(last_name))  >= 1),
  contact_number  varchar(20)  check (
                    contact_number is null
                    or contact_number ~ '^[0-9+()[:space:]-]{7,20}$'),
  address         varchar(150) not null check (length(btrim(address)) >= 3),
  date_registered date         not null default current_date,
  created_at      timestamptz  not null default now(),
  updated_at      timestamptz  not null default now()
);

create table public.farm (
  farm_id       integer generated by default as identity primary key,
  farmer_id     integer      not null references public.farmer(farmer_id)
                  on update cascade on delete restrict,
  farm_name     varchar(100) not null check (length(btrim(farm_name)) >= 1),
  location      varchar(150) not null check (length(btrim(location)) >= 3),
  area_hectares numeric(8,2) not null check (area_hectares > 0 and area_hectares <= 10000),
  soil_id       smallint     not null references public.soil_type(soil_id),
  irrigation_id smallint     not null references public.irrigation_type(irrigation_id),
  created_at    timestamptz  not null default now(),
  updated_at    timestamptz  not null default now(),
  constraint farm_name_per_farmer_unique unique (farmer_id, farm_name)
);

create table public.crop (
  crop_id              integer generated by default as identity primary key,
  crop_name            varchar(80) not null unique check (length(btrim(crop_name)) >= 1),
  variety              varchar(80),
  category_id          smallint    not null references public.crop_category(category_id),
  growing_period_days  integer     not null check (growing_period_days > 0 and growing_period_days <= 1500),
  season_id            smallint    not null references public.growing_season(season_id),
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);

create table public.planting (
  planting_id           integer generated by default as identity primary key,
  farm_id               integer      not null references public.farm(farm_id)
                          on update cascade on delete restrict,
  crop_id               integer      not null references public.crop(crop_id)
                          on update cascade on delete restrict,
  planting_date         date         not null,
  area_planted          numeric(8,2) not null check (area_planted > 0),
  seed_quantity         numeric(8,2) not null check (seed_quantity >= 0),
  expected_harvest_date date,
  status_id             smallint     not null references public.planting_status(status_id),
  created_at            timestamptz  not null default now(),
  updated_at            timestamptz  not null default now(),
  constraint planting_dates_logical
    check (expected_harvest_date is null or expected_harvest_date >= planting_date)
);

-- selling_price_per_kg is the price at the time of THIS harvest (it differs
-- between harvests of the same crop), so it correctly belongs to HARVEST.
create table public.harvest (
  harvest_id           integer generated by default as identity primary key,
  planting_id          integer       not null references public.planting(planting_id)
                         on update cascade on delete restrict,
  harvest_date         date          not null,
  quantity_kg          numeric(10,2) not null check (quantity_kg > 0),
  selling_price_per_kg numeric(10,2) not null check (selling_price_per_kg >= 0),
  grade_id             smallint      not null references public.quality_grade(grade_id),
  remark_id            smallint      not null references public.harvest_remark(remark_id),
  created_at           timestamptz   not null default now(),
  updated_at           timestamptz   not null default now()
);

