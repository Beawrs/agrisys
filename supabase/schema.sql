create table if not exists public.farmer (
  farmer_id   bigint generated by default as identity primary key,
  first_name  text    not null check (length(btrim(first_name)) between 1 and 60),
  last_name   text    not null check (length(btrim(last_name))  between 1 and 60),
  sex_id      smallint not null references public.sex(sex_id),
  birth_date  date     check (birth_date >= date '1900-01-01'),
  contact_no  text     check (
                contact_no is null
                or contact_no ~ '^[0-9+()[:space:]-]{7,20}$'
              ),
  address     text    not null check (length(btrim(address)) between 5 and 200),
  created_at  timestamptz not null default now(),
  updated_at  timestamptz not null default now()
);

create table if not exists public.farm (
  farm_id       bigint generated by default as identity primary key,
  farmer_id     bigint not null references public.farmer(farmer_id)
                  on update cascade on delete restrict,
  farm_name     text   not null check (length(btrim(farm_name)) between 1 and 100),
  location      text   not null check (length(btrim(location)) between 3 and 200),
  area_hectares numeric(10,2) not null check (area_hectares > 0 and area_hectares <= 10000),
  irrigation_id smallint not null references public.irrigation_type(irrigation_id),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint farm_name_per_farmer_unique unique (farmer_id, farm_name)
);

create table if not exists public.crop (
  crop_id       bigint generated by default as identity primary key,
  crop_name     text   not null unique check (length(btrim(crop_name)) between 1 and 80),
  variety       text   check (variety is null or length(btrim(variety)) <= 80),
  category_id   smallint not null references public.crop_category(category_id),
  unit_id       smallint not null references public.crop_unit(unit_id),
  selling_price numeric(12,2) not null check (selling_price >= 0),
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

create table if not exists public.planting (
  planting_id           bigint generated by default as identity primary key,
  farm_id               bigint not null references public.farm(farm_id)
                          on update cascade on delete restrict,
  crop_id               bigint not null references public.crop(crop_id)
                          on update cascade on delete restrict,
  planting_date         date   not null,
  expected_harvest_date date,
  area_planted          numeric(10,2) not null check (area_planted > 0),
  status_id             smallint not null references public.planting_status(status_id),
  remarks               text   check (remarks is null or length(remarks) <= 500),
  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),
  constraint planting_dates_logical
    check (expected_harvest_date is null or expected_harvest_date >= planting_date)
);

create table if not exists public.harvest (
  harvest_id        bigint generated by default as identity primary key,
  planting_id       bigint not null references public.planting(planting_id)
                      on update cascade on delete restrict,
  harvest_date      date   not null,
  quantity_harvested numeric(12,2) not null check (quantity_harvested > 0),
  grade_id          smallint not null references public.quality_grade(grade_id),
  remark_id         smallint not null references public.harvest_remark(remark_id),
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

