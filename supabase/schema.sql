-- ---------- lookup tables ----------
do $$
declare
  t text;
begin
  foreach t in array array[
    'sex', 'irrigation_type', 'crop_category', 'crop_unit',
    'planting_status', 'quality_grade', 'harvest_remark'
  ]
  loop
    execute format('drop policy if exists "lookup read" on public.%I', t);
    execute format('drop policy if exists "lookup insert" on public.%I', t);
    execute format('drop policy if exists "lookup update" on public.%I', t);
    execute format('drop policy if exists "lookup delete" on public.%I', t);
    execute format('create policy "lookup read"   on public.%I for select to authenticated using (true)', t);
    execute format('create policy "lookup insert" on public.%I for insert to authenticated with check (public.is_admin())', t);
    execute format('create policy "lookup update" on public.%I for update to authenticated using (public.is_admin()) with check (public.is_admin())', t);
    execute format('create policy "lookup delete" on public.%I for delete to authenticated using (public.is_admin())', t);
  end loop;
end;
$$;

-- ---------- core transaction tables ----------
do $$
declare
  t text;
begin
  foreach t in array array['farmer', 'farm', 'crop', 'planting', 'harvest']
  loop
    execute format('drop policy if exists "records read" on public.%I', t);
    execute format('drop policy if exists "records insert" on public.%I', t);
    execute format('drop policy if exists "records update" on public.%I', t);
    execute format('drop policy if exists "records delete" on public.%I', t);
    execute format('create policy "records read"   on public.%I for select to authenticated using (true)', t);
    execute format('create policy "records insert" on public.%I for insert to authenticated with check (true)', t);
    execute format('create policy "records update" on public.%I for update to authenticated using (true) with check (true)', t);
    execute format('create policy "records delete" on public.%I for delete to authenticated using (public.is_admin())', t);
  end loop;
end;
$$;

