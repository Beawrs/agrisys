create view public.v_farmer with (security_invoker = true) as
select
  f.farmer_id,
  f.first_name,
  f.last_name,
  f.first_name || ' ' || f.last_name as full_name,
  f.sex_id,
  s.sex_description,
  f.birth_date,
  f.contact_no,
  f.address,
  f.created_at,
  f.updated_at,
  (select count(*) from public.farm fm where fm.farmer_id = f.farmer_id)::int as farm_count
from public.farmer f
join public.sex s on s.sex_id = f.sex_id;

create view public.v_farm with (security_invoker = true) as
select
  fm.farm_id,
  fm.farm_name,
  fm.farmer_id,
  f.first_name || ' ' || f.last_name as farmer_name,
  fm.location,
  fm.area_hectares,
  fm.irrigation_id,
  it.irrigation_description,
  fm.created_at,
  fm.updated_at,
  (select count(*) from public.planting p where p.farm_id = fm.farm_id)::int as planting_count
from public.farm fm
join public.farmer f          on f.farmer_id = fm.farmer_id
join public.irrigation_type it on it.irrigation_id = fm.irrigation_id;

create view public.v_crop with (security_invoker = true) as
select
  c.crop_id,
  c.crop_name,
  c.variety,
  c.category_id,
  cc.category_description,
  c.unit_id,
  cu.unit_description,
  cu.unit_symbol,
  c.selling_price,
  c.created_at,
  c.updated_at,
  (select count(*) from public.planting p where p.crop_id = c.crop_id)::int as planting_count
from public.crop c
join public.crop_category cc on cc.category_id = c.category_id
join public.crop_unit cu     on cu.unit_id = c.unit_id;

create view public.v_planting with (security_invoker = true) as
select
  p.planting_id,
  p.farm_id,
  fm.farm_name,
  fm.farmer_id,
  f.first_name || ' ' || f.last_name as farmer_name,
  p.crop_id,
  c.crop_name,
  c.variety,
  p.planting_date,
  p.expected_harvest_date,
  p.area_planted,
  p.status_id,
  ps.status_description,
  p.remarks,
  p.created_at,
  p.updated_at,
  (select count(*) from public.harvest h where h.planting_id = p.planting_id)::int as harvest_count
from public.planting p
join public.farm fm           on fm.farm_id = p.farm_id
join public.farmer f          on f.farmer_id = fm.farmer_id
join public.crop c            on c.crop_id = p.crop_id
join public.planting_status ps on ps.status_id = p.status_id;

create view public.v_harvest with (security_invoker = true) as
select
  h.harvest_id,
  h.planting_id,
  p.planting_date,
  p.farm_id,
  fm.farm_name,
  p.crop_id,
  c.crop_name,
  h.harvest_date,
  h.quantity_harvested,
  c.unit_id,
  cu.unit_description,
  cu.unit_symbol,
  h.grade_id,
  qg.grade_description,
  h.remark_id,
  hr.remark_description,
  c.selling_price,
  round(h.quantity_harvested * c.selling_price, 2) as estimated_value,
  h.created_at,
  h.updated_at
from public.harvest h
join public.planting p       on p.planting_id = h.planting_id
join public.farm fm          on fm.farm_id = p.farm_id
join public.crop c           on c.crop_id = p.crop_id
join public.crop_unit cu     on cu.unit_id = c.unit_id
join public.quality_grade qg on qg.grade_id = h.grade_id
join public.harvest_remark hr on hr.remark_id = h.remark_id;

create view public.v_planting_status_summary with (security_invoker = true) as
select
  ps.status_id,
  ps.status_description,
  count(p.planting_id)::int as planting_count
from public.planting_status ps
left join public.planting p on p.status_id = ps.status_id
group by ps.status_id, ps.status_description;

create view public.v_harvest_monthly with (security_invoker = true) as
select
  to_char(h.harvest_date, 'YYYY-MM') as month,
  count(*)::int as harvest_count,
  sum(h.quantity_harvested) as total_quantity,
  round(sum(h.quantity_harvested * c.selling_price), 2) as total_value
from public.harvest h
join public.planting p on p.planting_id = h.planting_id
join public.crop c     on c.crop_id = p.crop_id
group by to_char(h.harvest_date, 'YYYY-MM');

