-- New Supabase Auth users automatically get a STAFF profile. The role is NOT
-- read from sign-up metadata, so nobody can grant themselves Administrator.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, email, full_name, role)
  values (
    new.id,
    coalesce(new.email, ''),
    coalesce(nullif(btrim(new.raw_user_meta_data ->> 'full_name'), ''), coalesce(new.email, 'User')),
    'staff'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- A harvest can never happen before its planting date.
create or replace function public.validate_harvest_date()
returns trigger
language plpgsql
as $$
declare
  planted_on date;
begin
  select planting_date into planted_on
  from public.planting
  where planting_id = new.planting_id;

  if planted_on is null then
    raise exception 'The selected planting record does not exist.';
  end if;

  if new.harvest_date < planted_on then
    raise exception 'Harvest date (%) cannot be earlier than the planting date (%).',
      new.harvest_date, planted_on;
  end if;

  return new;
end;
$$;

create trigger trg_harvest_date_check
  before insert or update of harvest_date, planting_id on public.harvest
  for each row execute function public.validate_harvest_date();

